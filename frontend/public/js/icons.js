/**
 * Returns an inline SVG string for the requested icon.
 *
 * @param {string} name - Icon identifier (e.g. 'calendar', 'building', 'user')
 * @param {number} [size=16] - Pixel size (width and height)
 * @param {string} [className=''] - Additional CSS classes
 * @returns {string} SVG HTML markup string
 */
export function icon(name, size = 16, className = "") {
  const renderer = ICON_PATHS[name];
  if (!renderer) {
    return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" class="svg-icon ${className}"><circle cx="12" cy="12" r="6"/></svg>`;
  }
  return renderer(size, className).trim();
}
